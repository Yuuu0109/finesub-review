// Verify an Actions artifact before it can be distributed. No private key needed.
import { readFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { createHash, createPublicKey, verify } from 'node:crypto';
import assert from 'node:assert/strict';
const root = resolve(import.meta.dirname, '..');
const config = JSON.parse(await readFile(join(root, 'frontend/src-tauri/tauri.conf.json'), 'utf8'));
const folder = resolve(process.argv[2] || join(root, 'output', `desktop-${config.version}`));
const manifest = JSON.parse(await readFile(join(folder, 'latest.json'), 'utf8'));
assert.match(manifest.version, /^\d+\.\d+\.\d+(?:-[A-Za-z0-9.-]+)?$/);
if (!process.argv.includes('--allow-previous-version')) assert.equal(manifest.version, config.version, 'Artifact version differs from source');
assert.deepEqual(Object.keys(manifest.platforms), ['windows-x86_64-portable']);
const entry = manifest.platforms['windows-x86_64-portable'];
const filename = `finesub-review-${manifest.version}-windows-x64-portable.exe`;
assert.equal(entry.url, `https://github.com/Yuuu0109/finesub-review/releases/download/v${manifest.version}/${filename}`);
const artifact = await readFile(join(folder, filename));
assert.ok(artifact.length >= 64 && artifact.length <= 256 * 1024 * 1024);
assert.equal(artifact.subarray(0, 2).toString(), 'MZ');
const pe = artifact.readUInt32LE(60);
assert.ok(pe <= artifact.length - 26);
assert.equal(artifact.subarray(pe, pe + 4).toString(), 'PE\0\0');
assert.equal(artifact.readUInt16LE(pe + 4), 0x8664, 'Must be Windows x64');
assert.equal(artifact.readUInt16LE(pe + 24), 0x20b, 'Must be PE32+');
assert.equal(entry.signature, (await readFile(join(folder, filename + '.sig'), 'utf8')).trim());
const expected = new Set([filename, filename + '.sig', 'latest.json']);
for (const line of (await readFile(join(folder, 'SHA256SUMS.txt'), 'utf8')).trim().split(/\r?\n/)) {
  const match = /^([a-f0-9]{64})  (.+)$/.exec(line);
  assert.ok(match, 'Invalid checksum line');
  const [, hash, name] = match;
  assert.ok(expected.delete(name), 'Unexpected or repeated checksum file');
  assert.equal(createHash('sha256').update(await readFile(join(folder, name))).digest('hex'), hash, name);
}
assert.equal(expected.size, 0, 'Missing checksum file');
const pubLines = Buffer.from(config.plugins.updater.pubkey, 'base64').toString().trim().split(/\r?\n/);
const pub = Buffer.from(pubLines[1], 'base64');
const lines = Buffer.from(entry.signature, 'base64').toString().trim().split(/\r?\n/);
assert.equal(lines.length, 4);
assert.equal(pub.length, 42);
const signature = Buffer.from(lines[1], 'base64');
assert.equal(signature.length, 74);
assert.equal(signature.subarray(0, 2).toString(), 'ED');
assert.deepEqual(signature.subarray(2, 10), pub.subarray(2, 10), 'Wrong signing key');
assert.ok(lines[2].startsWith('trusted comment: '));
const key = createPublicKey({ key: Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), pub.subarray(10)]), format: 'der', type: 'spki' });
const valid = data => verify(null, createHash('blake2b512').update(data).digest(), key, signature.subarray(10));
assert.equal(valid(artifact), true, 'Invalid portable signature');
assert.equal(verify(null, Buffer.concat([signature.subarray(10), Buffer.from(lines[2].slice('trusted comment: '.length))]), key, Buffer.from(lines[3], 'base64')), true, 'Invalid signed comment');
const tampered = Buffer.from(artifact); tampered[artifact.length - 1] ^= 1;
assert.equal(valid(tampered), false, 'Modified executable must be rejected');
console.log(JSON.stringify({ version: manifest.version, filename, bytes: artifact.length, sha256: createHash('sha256').update(artifact).digest('hex'), checksums: 'PASS', signature: 'PASS', tamperRejection: 'PASS' }, null, 2));
